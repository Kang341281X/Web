/**
 * 操作列宽度按按钮数量估算。
 * admin.css 把表格内 link 按钮改成了胶囊样式（左右 10px 内边距 + 按钮间 6px 间距），
 * 2 个字的按钮实测约 50px：1 个按钮 68 / 2 个 124 / 3 个 180。
 * 按钮文字更长（如「更换二维码」）或含上传控件时请在页面里单独给更大的固定宽度。
 */
export function actionColWidth(buttonCount) {
  return 12 + buttonCount * 56
}
